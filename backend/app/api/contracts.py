"""The run contracts the frontend is built against, exported as one JSON file.

`scripts/export_contracts.py` writes it to `frontend/src/contracts/run-contracts.json`; a backend
test fails if the committed file differs from what the models produce, and a frontend test fails
if the zod schemas disagree with it. The file is never edited by hand.
"""

import json
from pathlib import Path
from typing import Any

from app.core.config import REPO_ROOT
from app.core.pipeline import PIPELINE_STEPS
from app.models.runs import FakeRunRequest, RunAccepted, run_event_adapter

CONTRACTS_PATH: Path = REPO_ROOT / "frontend" / "src" / "contracts" / "run-contracts.json"


def build_contracts() -> dict[str, Any]:
    return {
        "$comment": (
            "Generated by backend/scripts/export_contracts.py from app/models/runs.py and "
            "app/core/pipeline.py. Do not edit; regenerate."
        ),
        "pipeline_steps": [
            {"number": s.number, "name": s.name, "title": s.title, "nodes": list(s.nodes)}
            for s in PIPELINE_STEPS
        ],
        "schemas": {
            # Requests are validated on the way in, responses and events serialised on the way out.
            "FakeRunRequest": FakeRunRequest.model_json_schema(mode="validation"),
            "RunAccepted": RunAccepted.model_json_schema(mode="serialization"),
            "RunEvent": run_event_adapter.json_schema(mode="serialization"),
        },
    }


def render_contracts() -> str:
    return json.dumps(build_contracts(), indent=2, sort_keys=True, ensure_ascii=True) + "\n"
